RAW_GLYPHS["G"][2] = "#.#"  # Fix typo in G definition


def build_tile(ch: str) -> bytes:
    """Builds a 16-byte SNES 2bpp tile for character ch."""
    rows = RAW_GLYPHS.get(ch, ["..."] * 8)
    body = []
    for r in rows:
        val = 0
        for bit, c in enumerate(r):
            if c == "#":
                val |= (1 << (3 - bit))
        body.append(val)
    while len(body) < 8:
        body.append(0)

    tile_bytes = bytearray(16)
    for y in range(8):
        b = body[y]
        prev_b = body[y - 1] if y > 0 else 0
        # Right and bottom-right shadow (within 4-bit nibble):
        s = ((b >> 1) | (prev_b >> 1) | prev_b) & 0x0F

        # Plane 0: Body of text
        p0 = (b << 4) | b
        # Plane 1: Body + Shadow
        p1 = ((b | s) << 4) | (b | s)

        tile_bytes[y * 2] = p0
        tile_bytes[y * 2 + 1] = p1

    return bytes(tile_bytes)


def generate_font_bin() -> bytes:
    chars = (
        [",", ".", " ", ":", "/", "-", "!"]
        + [chr(ord("0") + i) for i in range(10)]
        + [chr(ord("A") + i) for i in range(26)]
        + [chr(ord("a") + i) for i in range(26)]
    )

    out = bytearray()
    for ch in chars:
        out.extend(build_tile(ch))

    assert len(out) == 69 * 16, f"Expected 1104 bytes, got {len(out)}"
    return bytes(out)


def main():
    font_data = generate_font_bin()
    OUTPUT_BIN.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT_BIN.write_bytes(font_data)
    print(f"Generated clean 8x8 menu font ({len(font_data)} bytes, 69 tiles) -> {OUTPUT_BIN.relative_to(ROOT_DIR)}")


if __name__ == "__main__":
    main()
